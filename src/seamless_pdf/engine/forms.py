"""Form fields (AcroForm widgets) on pikepdf. Text/choice appearances are
generated by qpdf; checkbox on/off appearances are drawn here."""
from __future__ import annotations

import re
from typing import Optional

import pikepdf

from .annots import annot_key
from .geom import Rect
from .util import EditError, as_rect, rect_list

_ID = re.compile(r"^w:(\d+):([A-Za-z0-9_-]+)$")
FIELD_TYPES = ("text", "checkbox", "combobox", "listbox", "radio")
FF_MULTILINE, FF_COMBO, FF_RADIO, FF_PUSH, FF_REQUIRED = 1 << 12, 1 << 17, 1 << 15, 1 << 16, 1 << 1


def _truthy(v) -> bool:
    if isinstance(v, bool):
        return v
    return str(v).strip().lower() not in ("", "0", "false", "off", "no", "unchecked")


def _inherited(w, key):
    node, depth = w, 0
    while node is not None and depth < 20:
        if key in node:
            return node[key]
        node = node.get("/Parent")
        depth += 1
    return None


def _field_of(w):
    """The terminal field dictionary for a widget (itself, or its parent)."""
    return w if "/T" in w or "/Parent" not in w else w.Parent


def _qualified_name(w) -> str:
    parts, node, depth = [], w, 0
    while node is not None and depth < 20:
        if "/T" in node:
            parts.append(str(node.T))
        node = node.get("/Parent")
        depth += 1
    return ".".join(reversed(parts))


def _ftype(w) -> str:
    ft = str(_inherited(w, "/FT") or "")
    ff = int(_inherited(w, "/Ff") or 0)
    if ft == "/Btn":
        return "radiobutton" if ff & FF_RADIO else "button" if ff & FF_PUSH else "checkbox"
    if ft == "/Ch":
        return "combobox" if ff & FF_COMBO else "listbox"
    if ft == "/Sig":
        return "signature"
    return "text"


def _on_state(w) -> Optional[str]:
    try:
        for k in w.AP.N.keys():
            if k != "/Off":
                return k.lstrip("/")
    except Exception:
        pass
    return None


def _check_ap(pdf: pikepdf.Pdf, w: float, h: float) -> pikepdf.Dictionary:
    zadb = pdf.make_indirect(pikepdf.Dictionary(Type=pikepdf.Name.Font, Subtype=pikepdf.Name.Type1,
                                                BaseFont=pikepdf.Name.ZapfDingbats))
    size = min(w, h) * 0.8

    def stream(on: bool):
        ops = f"q 0.97 0.97 0.99 rg 0 0 {w:.2f} {h:.2f} re f 0.6 0.62 0.66 RG 0.8 w 0.4 0.4 {w - .8:.2f} {h - .8:.2f} re S Q\n"
        if on:
            ops += f"q BT /ZaDb {size:.2f} Tf 0 g {(w - size * 0.75) / 2:.2f} {(h - size * 0.7) / 2:.2f} Td (4) Tj ET Q\n"
        s = pikepdf.Stream(pdf, ops.encode())
        s.Type, s.Subtype = pikepdf.Name.XObject, pikepdf.Name.Form
        s.BBox = [0, 0, w, h]
        s.Resources = pikepdf.Dictionary(Font=pikepdf.Dictionary(ZaDb=zadb))
        return pdf.make_indirect(s)
    return pikepdf.Dictionary(N=pikepdf.Dictionary(Yes=stream(True), Off=stream(False)))


class FormOps:
    def _widgets(self, page_no: int):
        page = self.page(page_no)
        for a in page.obj.get("/Annots", []) or []:
            try:
                if str(a.get("/Subtype")) == "/Widget":
                    yield a
            except Exception:
                continue

    def _field_public(self, page_no: int, w) -> dict:
        P = self.model(page_no).P
        ft = _ftype(w)
        f = _field_of(w)
        v = _inherited(w, "/V")
        d = {"id": f"w:{page_no}:{annot_key(w)}", "kind": "field", "page": page_no, "field_type": ft,
             "name": _qualified_name(w), "label": str(f.get("/TU")) if "/TU" in f else None,
             "value": str(v) if v is not None else "",
             "bbox": rect_list(Rect.of([float(x) for x in w.Rect]).transform(P)), "movable": True}
        if ft in ("checkbox", "radiobutton"):
            on = _on_state(w)
            d["on_state"] = on
            d["value"] = str(w.get("/AS", "/Off")).lstrip("/") not in ("Off", "")
        opt = _inherited(w, "/Opt")
        if opt is not None:
            d["options"] = [str(o[1] if isinstance(o, pikepdf.Array) else o) for o in opt]
            d["value"] = str(v) if v is not None else ""
        return d

    def field_objects(self, page_no: int) -> list[dict]:
        return [self._field_public(page_no, w) for w in self._widgets(page_no)]

    def list_form_fields(self) -> dict:
        with self.lock:
            fields = []
            for p in range(self.page_count):
                fields.extend(self.field_objects(p))
            return {"count": len(fields), "fields": fields}

    def _resolve_field(self, fid: str):
        m = _ID.match(fid or "")
        if not m:
            raise EditError(f"{fid!r} is not a form field id")
        page_no, key = int(m.group(1)), m.group(2)
        for w in self._widgets(page_no):
            if annot_key(w) == key:
                return page_no, w
        raise EditError(f"field {fid!r} is no longer on page {page_no}")

    def _acroform(self) -> pikepdf.Dictionary:
        root = self.pdf.Root
        if "/AcroForm" not in root:
            root.AcroForm = self.pdf.make_indirect(pikepdf.Dictionary(Fields=pikepdf.Array()))
        af = root.AcroForm
        if "/DR" not in af:
            af.DR = pikepdf.Dictionary()
        if "/Font" not in af.DR:
            af.DR.Font = pikepdf.Dictionary()
        if "/Helv" not in af.DR.Font:
            af.DR.Font.Helv = self.pdf.make_indirect(pikepdf.Dictionary(
                Type=pikepdf.Name.Font, Subtype=pikepdf.Name.Type1, BaseFont=pikepdf.Name.Helvetica,
                Encoding=pikepdf.Name.WinAnsiEncoding))
        if "/DA" not in af:
            af.DA = pikepdf.String("/Helv 0 Tf 0 g")
        return af

    def _regen(self) -> None:
        """Have qpdf (re)build text/choice field appearances."""
        af = self._acroform()
        af.NeedAppearances = True
        try:
            self.pdf.acroform.generate_appearances_if_needed()
        except Exception:
            pass  # viewers will still regenerate from NeedAppearances
        if "/NeedAppearances" in af:
            del af["/NeedAppearances"]

    def set_field_value(self, fid: str, value) -> dict:
        with self.transaction("Fill field"):
            page_no, w = self._resolve_field(fid)
            ft = _ftype(w)
            f = _field_of(w)
            if ft == "checkbox":
                on = _on_state(w) or "Yes"
                state = pikepdf.Name("/" + on) if _truthy(value) else pikepdf.Name.Off
                f.V = state
                w.AS = state
            elif ft == "radiobutton":
                parent = w.get("/Parent", w)
                want = str(value)
                states = {(_on_state(k) or ""): k for k in parent.get("/Kids", [w])}
                if want not in states and _truthy(value):
                    want = _on_state(w) or want
                parent.V = pikepdf.Name("/" + want) if want in states else pikepdf.Name.Off
                for st, k in states.items():
                    k.AS = pikepdf.Name("/" + st) if st == want else pikepdf.Name.Off
            elif ft in ("combobox", "listbox"):
                opts = [str(o[1] if isinstance(o, pikepdf.Array) else o) for o in (_inherited(w, "/Opt") or [])]
                if opts and str(value) not in opts:
                    raise EditError(f"{value!r} is not one of {opts}")
                f.V = pikepdf.String(str(value))
            elif ft == "signature":
                raise EditError("signature fields cannot be filled here")
            else:
                f.V = pikepdf.String("" if value is None else str(value))
            self._regen()
            self._touch(page_no)
            return {"id": fid, "value": self._field_public(page_no, w)["value"]}

    def add_form_field(self, page_no: int, rect, field_type: str, name: str, value=None,
                       options: Optional[list] = None, font_size: float = 0) -> dict:
        ft = (field_type or "").lower()
        if ft not in FIELD_TYPES:
            raise EditError(f"field_type must be one of {', '.join(FIELD_TYPES)}")
        if not name:
            raise EditError("a field needs a name")
        with self.transaction("Add field"):
            page = self.page(page_no)
            af = self._acroform()
            r = as_rect(rect).transform(self.model(page_no).P.inverse())
            import uuid
            d = pikepdf.Dictionary(Type=pikepdf.Name.Annot, Subtype=pikepdf.Name.Widget, F=4,
                                   NM=pikepdf.String(uuid.uuid4().hex[:16]),
                                   T=pikepdf.String(str(name)), Rect=r.list(), P=page.obj,
                                   DA=pikepdf.String(f"/Helv {float(font_size or 0):g} Tf 0 g"),
                                   MK=pikepdf.Dictionary(BC=[0.6, 0.62, 0.66], BG=[0.97, 0.97, 0.99]))
            if ft in ("checkbox", "radio"):
                d.FT = pikepdf.Name.Btn
                if ft == "radio":
                    d.Ff = FF_RADIO
                d.AP = _check_ap(self.pdf, r.width, r.height)
                on = _truthy(value) if value is not None else False
                d.V = d.AS = pikepdf.Name.Yes if on else pikepdf.Name.Off
            elif ft in ("combobox", "listbox"):
                d.FT = pikepdf.Name.Ch
                if ft == "combobox":
                    d.Ff = FF_COMBO
                opts = [str(o) for o in (options or [])] or ["Option 1"]
                d.Opt = pikepdf.Array([pikepdf.String(o) for o in opts])
                d.V = pikepdf.String(str(value) if value is not None else opts[0])
            else:
                d.FT = pikepdf.Name.Tx
                if value is not None:
                    d.V = pikepdf.String(str(value))
            w = self.pdf.make_indirect(d)
            if "/Annots" not in page.obj:
                page.obj.Annots = pikepdf.Array()
            page.obj.Annots.append(w)
            af.Fields.append(w)
            self._regen()
            self._touch(page_no)
            return {"id": f"w:{page_no}:{annot_key(w)}"}

    def delete_field(self, fid: str) -> dict:
        with self.transaction("Delete field"):
            page_no, w = self._resolve_field(fid)
            page = self.page(page_no)
            page.obj.Annots = pikepdf.Array([a for a in page.obj.Annots if a.objgen != w.objgen])
            af = self.pdf.Root.get("/AcroForm")
            if af is not None and "/Fields" in af:
                af.Fields = pikepdf.Array([f for f in af.Fields if f.objgen != w.objgen])
            parent = w.get("/Parent")
            if parent is not None and "/Kids" in parent:
                parent.Kids = pikepdf.Array([k for k in parent.Kids if k.objgen != w.objgen])
            self._touch(page_no)
            return {"deleted": fid}

    def set_field_rect(self, fid: str, rect) -> str:
        with self.transaction("Resize field"):
            page_no, w = self._resolve_field(fid)
            r = as_rect(rect).transform(self.model(page_no).P.inverse())
            w.Rect = r.list()
            if _ftype(w) in ("checkbox", "radiobutton"):
                w.AP = _check_ap(self.pdf, r.width, r.height)
            elif "/AP" in w:
                del w["/AP"]
            self._regen()
            self._touch(page_no)
            return fid

    def move_field(self, fid: str, dx: float, dy: float) -> str:
        page_no, w = self._resolve_field(fid)
        r = Rect.of([float(v) for v in w.Rect]).transform(self.model(page_no).P)
        return self.set_field_rect(fid, [r.x0 + dx, r.y0 + dy, r.x1 + dx, r.y1 + dy])

    # -- flattening (fields and/or annotations) ----------------------------------------------
    def bake(self, annots: bool = True, widgets: bool = True) -> list[int]:
        """Draw appearances into the page content and remove the objects."""
        if widgets and "/AcroForm" in self.pdf.Root:
            self._regen()
        pages = []
        for p in range(self.page_count):
            page = self.page(p)
            keep, changed = [], False
            for a in list(page.obj.get("/Annots", []) or []):
                sub = str(a.get("/Subtype"))
                take = (widgets and sub == "/Widget") or (annots and sub not in ("/Widget", "/Link", "/Popup"))
                if not take:
                    keep.append(a)
                    continue
                changed = True
                ap = a.get("/AP")
                n = ap.get("/N") if ap is not None else None
                if isinstance(n, pikepdf.Dictionary) and not isinstance(n, pikepdf.Stream):
                    n = n.get(a.get("/AS", pikepdf.Name.Off))
                if isinstance(n, pikepdf.Stream) and int(a.get("/F", 0)) & 2 == 0:
                    rect = pikepdf.Rectangle(*[float(v) for v in a.Rect])
                    try:
                        page.add_overlay(n, rect, shrink=True, expand=True)
                    except Exception:
                        pass
            if changed:
                page.obj.Annots = pikepdf.Array(keep)
                pages.append(p)
        if widgets and "/AcroForm" in self.pdf.Root:
            del self.pdf.Root["/AcroForm"]
        return pages

    def flatten_forms(self) -> dict:
        with self.transaction("Flatten form"):
            if not any(list(self._widgets(p)) for p in range(self.page_count)):
                raise EditError("the document has no form fields")
            pages = self.bake(annots=False, widgets=True)
            self._touch(*pages)
            return {"flattened_pages": pages}
